def _schema(**kwargs):
    return UnitySchema(project_name="SelectionFixture", game_type="3D",
                       platform="pc", render_pipeline="URP", **kwargs)


def _emit(schema, root: Path):
    subsystems = _compose_subsystems(schema)
    merge_authored_code(subsystems, schema.microgens)
    MicroComposer(schema.project_name, project_config={"audio": {"backend": "dsp"}}).emit(
        subsystems, root, has_game_manager=False)
    # Compare every generated byte, including audio, manifests and .meta GUIDs.
    return {str(path.relative_to(root)): path.read_bytes()
            for path in sorted(root.rglob("*")) if path.is_file()}


@pytest.mark.parametrize("game_type,locomotion,brief,expected", [
    ("3D", "drive", "Ride a motorcycle with lean angle and inventory.", "vehicle_bike"),
    ("3D", "drive", "Race a hovercraft with inventory.", "vehicle_hover"),
    ("3D", "walk", "Climb a vertical wall with handholds.", "climbing"),
    ("2D", "walk", "Ride a bike over moving platforms.", "2d_platformer"),
])
def test_saved_choices_make_all_micro_output_independent_of_raw_prompt(
        tmp_path, game_type, locomotion, brief, expected, monkeypatch):
    schema = _schema(locomotion=locomotion, features=["audio"])
    schema.game_type = game_type
    persist_selection(schema, brief)
    saved = UnitySchema.model_validate_json(schema.model_dump_json())
    assert next(s.variant for s in selected_subsystems(saved)
                if s.kind == "controller") == expected
    # A post-selection codegen path must never call the selector again.
    monkeypatch.setattr("src.unity_compose_selection.select_subsystems",
                        lambda *a, **kw: pytest.fail("generation reselected micros"))
    saved.meta["user_prompt"] = brief
    a = _emit(saved, tmp_path / "a")
    saved.meta["user_prompt"] = "No bikes. Swim in a horror maze. Flying enemies take cover."
    saved.meta["concept"] = "A completely different helicopter game."
    saved.description = "No inventory, no climbing, no moving platforms."
    b = _emit(saved, tmp_path / "b")
    assert a
    assert any(name.endswith(".cs") for name in a)
    assert a == b


def test_selection_records_controller_and_added_micro_disagreements():
    schema = _schema(locomotion="drive")
    messages = persist_selection(schema, "A motorcycle with an inventory.")
    record = schema.meta[SELECTION_KEY]
    controller = next(d for d in record["disagreements"]
                      if (d.get("brief_selected") or {}).get("kind") == "controller")
    assert controller["schema_derived"]["variant"] == "vehicle_car"
    assert controller["brief_selected"]["variant"] == "vehicle_bike"
    inventory = next(d for d in record["disagreements"]
                     if (d.get("brief_selected") or {}).get("kind") == "inventory")
    assert inventory["schema_derived"] is None
    assert inventory["resolution"] == "brief_selected"
    assert messages


def test_classifier_disagreement_preserves_both_values_and_resolution():
    schema = _schema(locomotion="walk")
    apply_intent(schema, classify("A swimming game underwater in the ocean."))
    conflict = next(d for d in schema.meta["intent_conflicts"] if d["field"] == "locomotion")
    assert conflict["schema_value"] == "walk"
    assert conflict["classifier_value"] == "swim"
    assert conflict["resolution"] == "classifier"
    persist_selection(schema, "")
    assert conflict in schema.meta[SELECTION_KEY]["disagreements"]


def test_protected_schema_value_records_classifier_disagreement():
    schema = _schema(locomotion="none")
    apply_intent(schema, classify("Drive a car in a racing game."))
    conflict = next(d for d in schema.meta["intent_conflicts"] if d["field"] == "locomotion")
    assert conflict["resolution"] == "schema"
    assert schema.locomotion == "none"


def test_legacy_schema_ignores_prompt_and_announces_missing_provenance(capsys):
    schema = _schema(locomotion="drive")
    schema.meta["user_prompt"] = "A motorcycle with inventory."
    a = selected_subsystems(schema)
    schema.meta["user_prompt"] = "A hovercraft with voiced NPCs."
    b = selected_subsystems(schema)
    assert a == b
    assert next(s.variant for s in a if s.kind == "controller") == "vehicle_car"
    assert "compose_selection missing" in capsys.readouterr().out
    assert SELECTION_KEY not in schema.meta


def test_replay_returns_independent_objects_and_never_mutates_saved_record():
    schema = _schema()
    persist_selection(schema, "Climb a vertical wall.")
    original = schema.model_dump_json()
    a = selected_subsystems(schema)
    a[0].variant = "first_person"
    a[0].options["arbitrary"] = ["mutation"]
    assert schema.model_dump_json() == original
    assert selected_subsystems(schema)[0].variant == "climbing"


