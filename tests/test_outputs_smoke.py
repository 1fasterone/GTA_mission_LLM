"""
Beta-gate smoke tests — runs against *real generated outputs* under output/
and output/unity/, not synthetic fixtures. The goal is "did the generator
produce something a tester can actually use?", not "does the code match an
expectation in isolation."

Run with:    pytest -m smoke
Skip with:   pytest -m "not smoke"   (default suite excludes nothing — these
                                       tests skip themselves when there are
                                       no outputs on disk yet)

Gates:
  - GTA C# structural parse (header, class : Script, GTA usings, no UNRESOLVED).
  - Schema round-trip: every *.schema.json re-validates against the current
    Pydantic models — catches schema drift.
  - Unity project structure: Assets/, Packages/manifest.json, ProjectSettings/,
    valid manifest dependencies, at least one .unity scene, ProjectVersion.txt
    matches Unity major version, no UNRESOLVED / unrendered Jinja braces.
"""

