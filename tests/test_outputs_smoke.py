# ── Unity project structure smoke ─────────────────────────────────────────────

_PKG_KEY_RE = re.compile(r"^com\.[a-z][a-z0-9._-]+$")
_UNITY_VER_RE = re.compile(r"^m_EditorVersion:\s*(\d{4}\.\d+\.\d+[a-z]?\d*)\s*$", re.M)


@pytest.mark.smoke
@pytest.mark.parametrize("project_dir", _unity_projects(),
                         ids=[p.name for p in _unity_projects()] or ["<no outputs>"])
def test_unity_project_structure(project_dir: Path) -> None:
    if not _unity_projects():
        pytest.skip("No Unity projects under output/unity/ — generate one first.")

    # Required top-level folders/files
    for required in ("Assets", "ProjectSettings", "Packages/manifest.json"):
        assert (project_dir / required).exists(), \
            f"{project_dir.name}: missing {required}"

    # ── manifest.json: dependency keys + non-empty values ─────────────────────
    manifest = json.loads((project_dir / "Packages" / "manifest.json").read_text(encoding="utf-8"))
    deps = manifest.get("dependencies") or {}
    assert deps, f"{project_dir.name}: manifest.json has no dependencies"
    bad_keys = [k for k in deps if not _PKG_KEY_RE.match(k)]
    assert not bad_keys, f"{project_dir.name}: malformed package keys: {bad_keys}"
    empty_vals = [k for k, v in deps.items() if not (isinstance(v, str) and v.strip())]
    assert not empty_vals, f"{project_dir.name}: empty package versions: {empty_vals}"

    # ── ProjectVersion.txt: declares a Unity major version ────────────────────
    pv_path = project_dir / "ProjectSettings" / "ProjectVersion.txt"
    assert pv_path.exists(), f"{project_dir.name}: missing ProjectVersion.txt"
    assert _UNITY_VER_RE.search(pv_path.read_text(encoding="utf-8")), \
        f"{project_dir.name}: ProjectVersion.txt missing m_EditorVersion"

    # ── At least one scene file under Assets/ ─────────────────────────────────
    scenes = list((project_dir / "Assets").rglob("*.unity"))
    assert scenes, f"{project_dir.name}: no .unity scene files under Assets/"


# Editor-managed directories (Unity creates these the first time a tester
# opens the project); they aren't generator output and frequently contain
# binary blobs that look like text and can match our leak regex by accident.
_EDITOR_MANAGED_DIRS = {"Library", "Logs", "Temp", "obj", "UserSettings"}


@pytest.mark.smoke
@pytest.mark.parametrize("project_dir", _unity_projects(),
                         ids=[p.name for p in _unity_projects()] or ["<no outputs>"])
def test_unity_no_unresolved_or_jinja_leak(project_dir: Path) -> None:
    """
    No UNRESOLVED tokens or unrendered Jinja tags in *generator-emitted* files
    under Assets/. Skips editor-managed subdirs (Library/Logs/Temp/…) and
    binary asset extensions.
    """
    if not _unity_projects():
        pytest.skip("No Unity projects under output/unity/ — generate one first.")

    leaked: list[str] = []
    for path in (project_dir / "Assets").rglob("*"):
        if not path.is_file():
            continue
        rel_parts = path.relative_to(project_dir).parts
        if any(part in _EDITOR_MANAGED_DIRS for part in rel_parts):
            continue
        if path.suffix.lower() in {".png", ".jpg", ".jpeg", ".tga", ".psd",
                                   ".wav", ".mp3", ".ogg", ".fbx", ".obj",
                                   ".blend", ".dll", ".pdb", ".exr", ".bin",
                                   ".ttf", ".otf"}:
            continue
        try:
            text = path.read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue
        if "UNRESOLVED" in text:
            leaked.append(f"UNRESOLVED in {path.relative_to(project_dir)}")
        if _JINJA_LEAK_RE.search(text):
            leaked.append(f"Jinja tag in {path.relative_to(project_dir)}")
    assert not leaked, f"{project_dir.name}:\n  " + "\n  ".join(leaked)


# ── 2D / 3D type-leak guard ──────────────────────────────────────────────────
#
# A 3D project's generated scripts must never reference 2D-physics types
# (Collider2D, Rigidbody2D, Physics2D) — even if `com.unity.modules.physics2d`
# is in the manifest. URP projects use auto-generated asmdefs that don't
# inherit the 2D module reference, so the C# compiler reports CS1069
# "type has been forwarded to assembly UnityEngine.Physics2DModule" and the
# whole scripts assembly fails to build. Caught real-world during private
# beta on a Unity 6000.0 / URP / 3D project.

_GAME_TYPE_RE = re.compile(r"GameType:\s*(\S+)", re.I)
_TWO_D_TYPES_RE = re.compile(r"\b(Collider2D|Rigidbody2D|Physics2D)\b")
_TWO_D_TYPES_OK_FOR = {"2D"}


def _detect_project_game_type(project_dir: Path) -> str | None:
    """Read GameType from any generated script's auto-header. None if unknown."""
    for cs_path in (project_dir / "Assets").rglob("*.cs"):
        try:
            head = cs_path.read_text(encoding="utf-8", errors="ignore").splitlines()[:5]
        except Exception:
            continue
        for line in head:
            m = _GAME_TYPE_RE.search(line)
            if m:
                return m.group(1)
    return None


@pytest.mark.smoke
@pytest.mark.parametrize("project_dir", _unity_projects(),
                         ids=[p.name for p in _unity_projects()] or ["<no outputs>"])
def test_unity_no_cross_dimension_physics_leak(project_dir: Path) -> None:
    """3D projects must not reference 2D physics types (and vice-versa)."""
    if not _unity_projects():
        pytest.skip("No Unity projects under output/unity/ — generate one first.")

    game_type = _detect_project_game_type(project_dir)
    if game_type is None:
        pytest.skip(f"{project_dir.name}: no GameType header — likely pre-template output.")

    if game_type in _TWO_D_TYPES_OK_FOR:
        return  # 2D project — 2D physics is correct.

    leaks: list[str] = []
    scripts_root = project_dir / "Assets" / "Scripts"
    if not scripts_root.exists():
        return
    for cs_path in scripts_root.rglob("*.cs"):
        rel_parts = cs_path.relative_to(project_dir).parts
        if any(part in _EDITOR_MANAGED_DIRS for part in rel_parts):
            continue
        try:
            text = cs_path.read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue
        for line_no, line in enumerate(text.splitlines(), 1):
            if _TWO_D_TYPES_RE.search(line):
                leaks.append(
                    f"{cs_path.relative_to(project_dir)}:{line_no}: {line.strip()[:80]}"
                )
    assert not leaks, (
        f"{project_dir.name} (GameType={game_type}) references 2D physics types — "
        "URP asmdefs will fail to resolve them:\n  " + "\n  ".join(leaks)
    )


# ── Manifest version sanity ──────────────────────────────────────────────────
#
# Unity rejects the entire manifest at import time if any single dependency
# can't be resolved on the registry. The historical default fallback in
# build_manifest_deps was the literal string "1.0.0" — which no current Unity
# official package actually publishes. Detecting it here keeps the bug from
# silently shipping again. Caught real-world during private beta.

@pytest.mark.smoke
@pytest.mark.parametrize("project_dir", _unity_projects(),
                         ids=[p.name for p in _unity_projects()] or ["<no outputs>"])
def test_unity_manifest_no_bogus_fallback_versions(project_dir: Path) -> None:
    if not _unity_projects():
        pytest.skip("No Unity projects under output/unity/ — generate one first.")
    manifest_path = project_dir / "Packages" / "manifest.json"
    if not manifest_path.exists():
        pytest.skip(f"{project_dir.name}: no manifest.json")
    deps = (json.loads(manifest_path.read_text(encoding="utf-8")).get("dependencies") or {})

    # "1.0.0" was the generator's fallback when no version was known — but some
    # real packages (built-in modules, com.unity.2d.sprite, com.unity.2d.tilemap,
    # …) genuinely publish 1.0.0. So a 1.0.0 is only "bogus" if the lookups DB
    # does NOT list 1.0.0 as a real version for that package.
    pkg_db = json.loads(
        (ROOT / "lookups" / "unity" / "packages.json").read_text(encoding="utf-8")
    ).get("versions", {})

    def _legit_at_one(pkg_id: str) -> bool:
        return "1.0.0" in (pkg_db.get(pkg_id) or {}).values()

    bad = [
        f"{k}={v!r}" for k, v in deps.items()
        if v == "1.0.0" and k.startswith("com.unity.")
        and not k.startswith("com.unity.modules.")
        and not _legit_at_one(k)
    ]
    assert not bad, (
        f"{project_dir.name}: manifest contains placeholder 1.0.0 versions "
        f"(no Unity official package ships at 1.0.0; this is the generator's "
        f"old fallback):\n  " + "\n  ".join(bad)
    )


