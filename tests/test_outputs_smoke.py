# ── GTA C# structural smoke ───────────────────────────────────────────────────

# Auto-generated header line shipped by templates/mission.cs.j2
_GTA_HEADER_RE = re.compile(r"^// Auto-generated by GTA5 Mission Pipeline")
_GTA_CLASS_RE  = re.compile(r"\bpublic\s+class\s+([A-Za-z_]\w*)\s*:\s*Script\b")
_REQUIRED_USINGS = ("using GTA;", "using GTA.Math;", "using GTA.Native;")
_JINJA_LEAK_RE = re.compile(r"\{\{\s*\w|\{%\s*\w")  # detects unrendered template tags


@pytest.mark.smoke
@pytest.mark.parametrize("script_path", _gta_scripts(),
                         ids=[p.stem for p in _gta_scripts()] or ["<no outputs>"])
def test_gta_script_structure(script_path: Path) -> None:
    if not _gta_scripts():
        pytest.skip("No GTA outputs under output/ — generate one first.")
    text = script_path.read_text(encoding="utf-8")
    first_line = text.splitlines()[0] if text else ""
    assert _GTA_HEADER_RE.match(first_line), \
        f"{script_path.name}: missing auto-generated header (got {first_line!r})"
    assert _GTA_CLASS_RE.search(text), \
        f"{script_path.name}: no 'public class X : Script' entry point"
    for required in _REQUIRED_USINGS:
        assert required in text, f"{script_path.name}: missing {required!r}"
    assert "UNRESOLVED" not in text, \
        f"{script_path.name}: UNRESOLVED model token leaked into generated C#"
    assert not _JINJA_LEAK_RE.search(text), \
        f"{script_path.name}: unrendered Jinja2 template tag in C# output"


