@pytest.mark.smoke
def test_unity_canonical_singleton_names() -> None:
    """
    Templates hard-reference GameManager / MeshBuilder / HealthSystem by name
    (UIManager & Collectible -> GameManager, ProceduralMesh -> MeshBuilder,
    Collectible -> HealthSystem). The programmatic fixer must force those class
    names regardless of what the LLM called the script, or referencing scripts
    fail with CS0246. Real-world catch from the headless `verify` compile gate
    (an isometric project's game_manager was named "BaseBuilder").
    """
    from src.unity_schema import UnitySchema
    from src.unity_pipeline import _programmatic_fix

    schema = UnitySchema.model_validate({
        "project_name": "CanonProbe", "company_name": "A", "description": "d",
        "game_type": "isometric", "platform": "pc", "render_pipeline": "URP",
        "unity_version": "6000.0",
        "scripts": [
            {"name": "BaseBuilder",     "type": "game_manager", "description": "g"},
            {"name": "OverlayManager",  "type": "ui_manager",   "description": "u"},
            {"name": "TerrainFactory",  "type": "mesh_builder", "description": "m"},
            {"name": "Vitals",          "type": "health",       "description": "h"},
            {"name": "SecondManager",   "type": "game_manager", "description": "g2"},
        ],
    })
    fixed = _programmatic_fix(schema)
    names = [s.name for s in fixed.scripts]
    assert "GameManager" in names
    assert "MeshBuilder" in names
    assert "HealthSystem" in names
    # The LLM's thematic names must be replaced, and only one singleton kept.
    assert "BaseBuilder" not in names
    assert names.count("GameManager") == 1


