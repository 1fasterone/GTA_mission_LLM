"""The composer's stale-output sweep.

Unity compiles every .cs under Assets/, so a recomposition whose cast changed
leaves the previous run's classes behind as live compilation units. Hit live on
Chromabreak: three shader controllers from a superseded run sat beside the ones
the build actually declared, plus objectives micros named after missions that no
longer exist.
"""
from __future__ import annotations

import time
from pathlib import Path

from src.unity_compose import MicroComposer

BANNER = "// Auto-generated by Unity Micro Pipeline — DO NOT EDIT\n"


def _composer() -> MicroComposer:
    return MicroComposer.__new__(MicroComposer)


def _write(scripts_dir: Path, names: list[str], *, banner: str = BANNER) -> None:
    scripts_dir.mkdir(parents=True, exist_ok=True)
    for n in names:
        (scripts_dir / f"{n}.cs").write_text(banner + "// x", encoding="utf-8")
        (scripts_dir / f"{n}.cs.meta").write_text("m", encoding="utf-8")


def _run(c: MicroComposer, root: Path, names: list[str]) -> list[str]:
    """One compose() cycle: snapshot, write this run's scripts, sweep."""
    root.mkdir(parents=True, exist_ok=True)
    before = c._cs_mtimes(root)
    time.sleep(0.01)                       # ensure a distinguishable mtime
    _write(root / "shader" / "Scripts", names)
    return c._sweep_stale_micros(root, before)


def test_a_superseded_runs_script_is_removed(tmp_path):
    root = tmp_path / "Micros"
    c = _composer()
    _run(c, root, ["ToonOutlineShell", "HolovaultScanline"])
    removed = _run(c, root, ["ToonOutlineShell"])

    sd = root / "shader" / "Scripts"
    assert removed == ["shader/Scripts/HolovaultScanline.cs"]
    assert sorted(p.name for p in sd.glob("*.cs")) == ["ToonOutlineShell.cs"]
    assert not (sd / "HolovaultScanline.cs.meta").exists(), "a .meta outlives nothing"


def test_it_sweeps_on_the_very_first_run_with_no_manifest(tmp_path):
    """The orphans predate the fix, so nothing recorded them. The file's own
    banner is what makes them recognisable without a manifest to consult."""
    root = tmp_path / "Micros"
    _write(root / "shader" / "Scripts", ["LeftBehind"])
    assert _run(_composer(), root, ["Current"]) == ["shader/Scripts/LeftBehind.cs"]
    assert (root / "shader" / "Scripts" / "Current.cs").is_file()


def test_a_file_the_composer_never_wrote_is_never_swept(tmp_path):
    root = tmp_path / "Micros"
    (root / "shader" / "Scripts").mkdir(parents=True)
    handmade = root / "shader" / "Scripts" / "MyOwn.cs"
    handmade.write_text("// mine, no banner", encoding="utf-8")

    c = _composer()
    _run(c, root, ["A", "B"])
    _run(c, root, ["A"])

    assert handmade.is_file(), "no banner, never ours, never removed"
    assert not (root / "shader" / "Scripts" / "B.cs").exists()


def test_a_script_this_run_rewrote_is_kept(tmp_path):
    root = tmp_path / "Micros"
    c = _composer()
    _run(c, root, ["A"])
    assert _run(c, root, ["A"]) == []
    assert (root / "shader" / "Scripts" / "A.cs").is_file()
