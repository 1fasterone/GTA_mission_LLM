"""
Generation salvage — pull the keeper files out of a throwaway generated Unity
project (schemas, hand-editable scripts, scenes, prefabs, models, audio, logs)
into an organized folder BEFORE the project directory gets deleted, and
promote any Sketchfab-sourced FBX the project downloaded into the shared,
centrally-cached Models/Sketchfab/ library + lookups/unity/sketchfab_catalog.json
so future generations can resolve them offline instead of re-fetching.

Both entry points are read-only with respect to the source project — neither
deletes nor mutates it. Deleting the project directory afterward is the
caller's job.
"""

from __future__ import annotations

import json
import re
import shutil
from datetime import datetime, timezone
from pathlib import Path

from .unity_asset_catalog import SKETCHFAB_RELPATH, tokenize, write_sketchfab_entry

# Directories inside a generated Unity project that are pure regenerable
# scaffolding/cache — never worth salvaging.
_SKIP_DIRS = frozenset({
    "library", "temp", "obj", "logs", "usersettings", ".vs", "build",
    "builds", "packagecache",
})

# (bucket, glob-suffix-matchers). Order matters — first match wins, so more
# specific buckets (scenes, prefabs, materials) are listed before the
# catch-all model/texture/audio buckets.
_BUCKET_RULES: list[tuple[str, tuple[str, ...]]] = [
    ("schemas",  (".schema.json", ".concept.txt", ".compile_map.json")),
    ("scenes",   (".unity",)),
    ("prefabs",  (".prefab",)),
    ("materials", (".mat",)),
    ("scripts",  (".cs",)),
    ("models",   (".fbx", ".obj", ".glb", ".gltf", ".blend")),
    ("textures", (".png", ".jpg", ".jpeg", ".tga", ".psd")),
    ("audio",    (".wav", ".mp3", ".ogg")),
    ("logs",     (".log",)),
    ("json",     (".json",)),
]


def _bucket_for(path: Path) -> str:
    name = path.name.lower()
    for bucket, suffixes in _BUCKET_RULES:
        if any(name.endswith(s) for s in suffixes):
            return bucket
    return "misc"


def resolve_project_dir(project: str, cfg: dict) -> Path:
    """A bare name resolves under unity_pipeline.unity_output_dir (config.yaml);
    an existing path (relative or absolute) is used as-is."""
    p = Path(project)
    if p.exists():
        return p
    unity_cfg = cfg.get("unity_pipeline", {}) if isinstance(cfg, dict) else {}
    root = Path(unity_cfg.get("unity_output_dir", "output/unity"))
    candidate = root / project
    if not candidate.exists():
        raise FileNotFoundError(
            f"no such Unity project: {project!r} (looked for a path, and for "
            f"{candidate} under unity_pipeline.unity_output_dir={root})")
    return candidate


def salvage_generation(project: str, dest_root: str | Path, cfg: dict) -> dict:
    """Copy every keeper file out of `project` into
    dest_root/<project_name>/<bucket>/<relative-path>, preserving the
    original relative path under each bucket so same-named files from
    different folders (e.g. two Building.fbx in different categories) never
    collide. Writes a MANIFEST.json alongside the copied files.

    Returns a summary dict: {"project_dir", "dest_dir", "counts": {bucket: n},
    "total_files", "total_bytes"}.
    """
    project_dir = resolve_project_dir(project, cfg)
    project_name = project_dir.name
    dest_dir = Path(dest_root) / project_name
    dest_dir.mkdir(parents=True, exist_ok=True)

    manifest: list[dict] = []
    counts: dict[str, int] = {}
    total_bytes = 0

    for path in sorted(project_dir.rglob("*")):
        if not path.is_file():
            continue
        if any(part.lower() in _SKIP_DIRS for part in path.relative_to(project_dir).parts):
            continue
        if path.name.endswith(".meta"):
            continue  # regenerated by Unity on next import; not worth salvaging

        bucket = _bucket_for(path)
        rel = path.relative_to(project_dir)
        out_path = dest_dir / bucket / rel
        out_path.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, out_path)

        size = path.stat().st_size
        total_bytes += size
        counts[bucket] = counts.get(bucket, 0) + 1
        manifest.append({
            "bucket": bucket,
            "source": str(rel.as_posix()),
            "dest": str((Path(bucket) / rel).as_posix()),
            "bytes": size,
        })

    manifest_path = dest_dir / "MANIFEST.json"
    manifest_path.write_text(
        json.dumps({
            "project": project_name,
            "source_dir": str(project_dir),
            "salvaged_at": datetime.now(timezone.utc).isoformat(),
            "files": manifest,
        }, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8")

    return {
        "project_dir": str(project_dir),
        "dest_dir": str(dest_dir),
        "counts": counts,
        "total_files": len(manifest),
        "total_bytes": total_bytes,
    }


# Sketchfab downloads are named "<slug>-<32-hex-uid>.fbx" by src/sketchfab_freeze.py
# (see _slug()/fbx_out there) — that suffix is how a promoted file is told apart
# from a first-party/Kenney placeholder (Building.fbx, Player.fbx, ...) sitting
# in the same project folder.
_SKETCHFAB_NAME_RE = re.compile(r"^(?P<slug>.+)-(?P<uid>[0-9a-f]{32})$", re.IGNORECASE)

_NEEDS_ATTRIBUTION = (
    "NEEDS ATTRIBUTION VERIFICATION — promoted from an already-generated "
    "project's Assets/Models folder, not from a live Sketchfab fetch, so the "
    "original author/license metadata wasn't available to freeze. Look up "
    "https://sketchfab.com/3d-models/{uid} before shipping/redistributing "
    "this model and fill in author/license by hand."
)


def find_promotable_sketchfab_models(project: str, cfg: dict) -> list[Path]:
    """FBX files under the project's Assets/Models (or Assets/Resources/Models)
    that look Sketchfab-sourced by filename, for a dry-run preview."""
    project_dir = resolve_project_dir(project, cfg)
    hits: list[Path] = []
    for search_root in ("Assets/Models", "Assets/Resources/Models/Sketchfab"):
        base = project_dir / search_root
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*.fbx")):
            if _SKETCHFAB_NAME_RE.match(path.stem):
                hits.append(path)
    # Same uid can appear under both search roots (Assets/Models/<Cat>/ and
    # the Resources mirror) — keep one copy, prefer the first root scanned.
    seen_uids: set[str] = set()
    deduped: list[Path] = []
    for path in hits:
        m = _SKETCHFAB_NAME_RE.match(path.stem)
        assert m is not None   # path was only added to `hits` after this same match
        uid = m.group("uid").lower()
        if uid in seen_uids:
            continue
        seen_uids.add(uid)
        deduped.append(path)
    return deduped


def promote_sketchfab_models(project: str, cfg: dict,
                              lookups_dir: str = "lookups",
                              cache_dir: str | Path = "Models/Sketchfab",
                              dry_run: bool = False) -> dict:
    """Copy every Sketchfab-looking FBX already sitting in `project` into the
    shared cache_dir (category inferred from its parent folder name) and
    freeze a best-effort catalog entry for each into sketchfab_catalog.json,
    skipping anything already cataloged by sketchfab_uid.

    This is a rescue path for models that were downloaded+converted for a
    specific project but never made it into the central cache (e.g. an older
    run, or a code path that skipped freezing) — NOT the normal flow, which
    already freezes on first fetch via src/sketchfab_freeze.py. Attribution
    can't be reconstructed from the FBX alone, so promoted entries are marked
    _NEEDS_ATTRIBUTION instead of guessing a license.
    """
    project_dir = resolve_project_dir(project, cfg)
    cache_dir = Path(cache_dir)
    catalog_path = Path(lookups_dir) / SKETCHFAB_RELPATH

    existing_uids: set[str] = set()
    try:
        existing = json.loads(catalog_path.read_text(encoding="utf-8"))
        existing_uids = {e.get("sketchfab_uid") for e in existing.get("entries", [])}
    except (FileNotFoundError, json.JSONDecodeError):
        pass

    promoted: list[dict] = []
    skipped: list[str] = []

    for path in find_promotable_sketchfab_models(project, cfg):
        m = _SKETCHFAB_NAME_RE.match(path.stem)
        assert m is not None   # find_promotable_sketchfab_models only returns matches
        slug, uid = m.group("slug"), m.group("uid").lower()

        if uid in existing_uids:
            skipped.append(f"{path.name} (already cataloged, uid {uid})")
            continue

        category = path.parent.name.lower()
        dest_dir = cache_dir / category / f"{slug}-{uid}"
        dest_fbx = dest_dir / f"{slug}-{uid}.fbx"

        if dest_fbx.exists():
            skipped.append(f"{path.name} (already present at {dest_fbx})")
            continue

        if not dry_run:
            dest_dir.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, dest_fbx)

        entry = {
            "filename": dest_fbx.name,
            "relpath": str(dest_fbx.relative_to(cache_dir).as_posix()),
            "root": str(cache_dir.as_posix()),
            "format": "fbx",
            "pack": "sketchfab",
            "source": "sketchfab",
            "category": category,
            "kind_hints": [category],
            "keywords": sorted(set(tokenize(slug))),
            "generic_score": 0,
            "scale": 1.0,
            "sketchfab_uid": uid,
            "sketchfab_url": f"https://sketchfab.com/3d-models/{uid}",
            "license": "unknown",
            "attribution": _NEEDS_ATTRIBUTION.format(uid=uid),
            "author": None,
            "author_url": None,
            "promoted_from_project": project_dir.name,
            "promoted_at": datetime.now(timezone.utc).isoformat(),
            "curated": False,
        }
        if not dry_run:
            write_sketchfab_entry(entry, catalog_path)
        promoted.append(entry)
        existing_uids.add(uid)

    return {
        "project_dir": str(project_dir),
        "cache_dir": str(cache_dir),
        "catalog_path": str(catalog_path),
        "promoted": promoted,
        "skipped": skipped,
        "dry_run": dry_run,
    }
