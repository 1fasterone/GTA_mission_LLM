def run(force: bool = False) -> int:
    if OUT.exists() and not force:
        count = sum(1 for line in OUT.read_text(encoding="utf-8").splitlines() if line.strip())
        print(f"[unity_genre_atoms] already present ({count} entries). Use --force to re-scrape.")
        return count

    OUT.parent.mkdir(parents=True, exist_ok=True)
    ok = err = 0
    with OUT.open("w", encoding="utf-8") as f:
        for raw in _ATOMS:
            try:
                entry = make_genre_atom_entry(raw)
                f.write(entry.to_jsonl() + "\n")
                ok += 1
            except Exception as e:
                print(f"  [skip] {raw.get('id','?')}: {e}", file=sys.stderr)
                err += 1

    print(f"[unity_genre_atoms] {ok} written, {err} skipped --> {OUT}")
    return ok


if __name__ == "__main__":
    run(force="--force" in sys.argv)
